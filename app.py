if analysis_mode == "Scoliosis Screening (Frontal/Back View)":
    st.title("Scoliosis Screening")
    st.write(
        "An experimental computer-vision prototype for estimating "
        "visible shoulder and hip posture asymmetry from front- or back-view photographs."
    )

    uploaded_file = st.file_uploader(
        "Upload a front-view or back-view photograph",
        type=["jpg", "jpeg", "png"],
        key="scoliosis_uploader"
    )

    if uploaded_file is not None:
        file_bytes = np.frombuffer(uploaded_file.getvalue(), dtype=np.uint8)
        image_bgr = cv2.imdecode(file_bytes, cv2.IMREAD_COLOR)

        if image_bgr is not None:
            image_rgb = cv2.cvtColor(image_bgr, cv2.COLOR_BGR2RGB)
            st.subheader("Uploaded Photograph")
            st.image(image_rgb, caption="Original Image", use_container_width=True)

            if st.button("Analyze Scoliosis Posture", key="scoliosis_btn"):
                with st.spinner("Detecting pose landmarks..."):
                    try:
                        analysis = analyze_scoliosis(image_rgb)
                        if analysis is None:
                            st.warning("No pose detected. Try a clear, well-lit image showing the person's upper body and hips.")
                        else:
                            st.session_state["scoliosis_analysis"] = analysis
                            st.success("Pose analysis completed.")
                    except Exception as error:
                        st.error(f"Analysis failed: {error}")
        else:
            st.error("Could not read this image. Please upload another.")

    if "scoliosis_analysis" in st.session_state:
        analysis = st.session_state["scoliosis_analysis"]

        st.subheader("Detected Shoulder and Hip Landmarks")
        st.image(analysis["image"], caption="Blue: shoulders | Green: hips", use_container_width=True)

        col1, col2 = st.columns(2)
        with col1:
            st.metric("Shoulder Tilt", f"{analysis['shoulder_tilt']:.2f}°")
        with col2:
            st.metric("Hip Tilt", f"{analysis['hip_tilt']:.2f}°")

        st.write("Shoulder vertical difference:", f"{analysis['shoulder_difference_px']} pixels")
        st.write("Hip vertical difference:", f"{analysis['hip_difference_px']} pixels")

        if analysis["quality_ok"]:
            st.success("Required landmarks passed the visibility check.")
        else:
            st.warning("Some landmarks have low visibility. Measurements may be unreliable.")

        fig, ax = plt.subplots(figsize=(7, 4))
        ax.bar(["Shoulder Tilt", "Hip Tilt"], [analysis["shoulder_tilt"], analysis["hip_tilt"]])
        ax.set_ylabel("Tilt angle (degrees)")
        ax.set_title("Postural Asymmetry Measurements")
        ax.set_ylim(0, max(10, analysis["shoulder_tilt"] + 2, analysis["hip_tilt"] + 2))
        st.pyplot(fig)
        plt.close(fig)

        st.subheader("Measurement Report")
        report_df = pd.DataFrame([{
            "Shoulder tilt (degrees)": round(analysis["shoulder_tilt"], 2),
            "Hip tilt (degrees)": round(analysis["hip_tilt"], 2),
            "Shoulder vertical difference (pixels)": analysis["shoulder_difference_px"],
            "Hip vertical difference (pixels)": analysis["hip_difference_px"],
            "Landmark visibility check": "Passed" if analysis["quality_ok"] else "Warning"
        }])
        st.dataframe(report_df, use_container_width=True)

        csv_data = report_df.to_csv(index=False).encode("utf-8")
        st.download_button(
            label="Download Scoliosis CSV Report",
            data=csv_data,
            file_name="scoliosis_posture_report.csv",
            mime="text/csv"
        )

        st.subheader("Preliminary Screening Interpretation")
        max_tilt = max(analysis["shoulder_tilt"], analysis["hip_tilt"])

        if not analysis["quality_ok"]:
            st.warning(
                "RESULT: INCONCLUSIVE\n\n"
                "Some body landmarks were not detected reliably. "
                "Please try another clear, straight-on photograph."
            )
        elif max_tilt >= 5:
            st.warning(
                "RESULT: POSTURAL ASYMMETRY OBSERVED\n\n"
                "The photograph shows a measurable difference in shoulder or hip alignment. "
                "This does not mean that the person has scoliosis. Please consult a qualified "
                "healthcare professional for further assessment."
            )
        else:
            st.info(
                "RESULT: NO MARKED ASYMMETRY DETECTED IN THIS PHOTO\n\n"
                "The measured shoulder and hip tilts are relatively small. "
                "However, this result does not rule out scoliosis. Consult a healthcare professional if concerned."
            )

        st.caption(
            "Research prototype only. The 5-degree value is an experimental software flag, "
            "not a validated scoliosis screening threshold."
        )

